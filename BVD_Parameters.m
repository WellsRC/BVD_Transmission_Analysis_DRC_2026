function [k_mle,p_mle,cfr_mle,k,p,cfr,R0_mle,R0] = BVD_Parameters(N_Samp)
if(N_Samp>1)
    rng(20260720)
end
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % Basic Reproduction Number
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % https://ars.els-cdn.com/content/image/1-s2.0-S1473309924003748-mmc1.pdf
    % (pg 21 DRC 1976  DRC 1995, DRC 2012, DRC 2014, DRC 2018-2020)

    X=[4.71 1.40 1.80 2.11 2.22 2.22 1.83 1.93 2.70 2.98 0.86 1.11 1.37 5.15 0.84 1.08 7.73 1.83 1.90];
    gp=gamfit(X);

    R0_mle = (gp(1)-1).*gp(2);
    R0=gamrnd(gp(1),gp(2),N_Samp,1);
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % Case fatality
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % https://pmc.ncbi.nlm.nih.gov/articles/PMC3294552/
    %https://pmc.ncbi.nlm.nih.gov/articles/PMC3321896/ 
    % https://journals.plos.org/plosone/article/file?id=10.1371/journal.pone.0052986&type=printable
    x=linspace(0,1,10001);
    L=betapdf(x,17,26).*betapdf(x,39,116-39).*betapdf(x,11,26-11);
    cfr_mle = x(L==max(L));
    w=cumsum(L)./sum(L);
    cfr=zeros(N_Samp,1);
    r=rand(N_Samp,1);
    for jj=1:N_Samp
        cfr(jj)=x(find(r(jj)<=w,1,"first"));
    end
   
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % Dispersion coefficients
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    k_mle =0.27;
    gp_k = lsqnonlin(@(x) [0.2 0.33] -gaminv([0.025 0.975],x(1),k_mle./(x(1)-1)),3,1,100);
    
    k = gamrnd(gp_k(1),k_mle./(gp_k(1)-1),N_Samp,1);
    
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % Negative binomial parameters 
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    p_mle = k_mle./(k_mle+R0_mle);
    p = k./(k+R0);
end